int get_digit_count(int num)
{
    if (num == 0)
        return 1;  // 0 有 1 位
    
    int count = 0;
    while (num != 0) {
        num /= 10;
        count++;
    }
    return count;
}

void show_data(struct tm *local, int data_x_start, int data_y_start, color_t color)
{
    int year=local->tm_year + 1900;
    char year_num[4]={0};
    year_num[0]=year/1000;
    year_num[1]=year/100%10;
    year_num[2]=year/10%10;
    year_num[3]=year%10;
    for(int i=0; i<4; i++)
        lcd_show_text_16x32(data_x_start+16*i+10, data_y_start, ch[year_num[i]], color);    
    lcd_show_text_32x32(data_x_start+16*4+10, data_y_start, text[11], color);

    char month=local->tm_mon + 1;
    char month_num[2]={0};
    month_num[0]=month/10;
    month_num[1]=month%10;
    for(int i=0; i<2; i++)
        lcd_show_text_16x32(data_x_start+16*(i+6)+10, data_y_start, ch[month_num[i]], color);    
    lcd_show_text_32x32(data_x_start+16*8+10, data_y_start, text[12], color);

    char day=local->tm_mday;
    int len=get_digit_count(day);
    char day_num[len];
    if(len==2)
    {
        day_num[0]=day/10;
        day_num[1]=day%10;
    }
    else
        day_num[0]=day;
    for(int i=0; i<len; i++)
        lcd_show_text_16x32(data_x_start+16*(i+10)+10, data_y_start, ch[day_num[i]], color);    
    lcd_show_text_32x32(data_x_start+16*(len+10)+10, data_y_start, text[7], color);
}

void show_time(struct tm *local, int time_x_start, int time_y_start, color_t color)
{
    char hour=local->tm_hour;
    int len=get_digit_count(hour);
    char hour_num[2];
    if(len==1)
    {
        hour_num[0]=0;
        hour_num[1]=hour;
    }
    else
    {
        hour_num[0]=hour/10;
        hour_num[1]=hour%10;
    }
    for(int i=0; i<2; i++)
        lcd_show_text_16x32(time_x_start+16*i+10, time_y_start, ch[hour_num[i]], color);    
    lcd_show_text_16x32(time_x_start+16*2+10, time_y_start, ch[10], color);

    char min=local->tm_min;
    len=get_digit_count(min);
    char min_num[2];
    if(len==1)
    {
        min_num[0]=0;
        min_num[1]=min;
    }
    else
    {

        min_num[0]=min/10;
        min_num[1]=min%10;
    }
    for(int i=0; i<2; i++)
        lcd_show_text_16x32(time_x_start+16*(i+3)+10, time_y_start, ch[min_num[i]], color);
}

