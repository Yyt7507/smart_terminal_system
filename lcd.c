int lcd_init(void)
{
    lcd_fd=open("/dev/fb0", O_RDWR);
    if(lcd_fd==-1)
    {
        perror("open fream buffer error");
        return -1;
    }
    pix=mmap(NULL, 1024*600*4, PROT_READ|PROT_WRITE, MAP_SHARED, lcd_fd, 0);
    if(pix==MAP_FAILED)
    {
        perror("map fream buffer error");
        return -1;
    }
    return 0;
}

int lcd_close(void)
{
    munmap(pix, 1024*600*4);
    close(lcd_fd);
}

int lcd_clear(void)
{
    color_t black={0, 0, 0};
    for(int y=0; y<600; y++)
    {
        for(int x=0; x<1024; x++)
        {
            pix[y][x].a=255;
            pix[y][x].color=black;
        }
    }
}

int lcd_color_block_drawing(int x_start, int y_start, int width, int height, color_t color)
{
    for(int y=y_start; y<600 && y<y_start+height; y++)
    {
        for(int x=x_start; x<1024 && x<x_start+width; x++)
        {
            pix[y][x].a=0;
            pix[y][x].color=color;
        }
    }
}

int lcd_draw_pic(char *picpath, int x_start, int y_start)
{
    int pic_fd=open(picpath, O_RDONLY);
    if(pic_fd==-1)
    {
        perror("open pic error");
        return -1;
    }

    int width=0, height=0;
    lseek(pic_fd, 18, SEEK_SET);
    read(pic_fd, &width, 4);
    read(pic_fd, &height, 4);

    color_t buf[width][height];
    lseek(pic_fd, 54, SEEK_SET);
    read(pic_fd, buf, sizeof(buf));

    for(int y=y_start; y<600 && y<y_start+height; y++)
    {
        for(int x=x_start; x<1024 && x<x_start+width; x++)
        {
            pix[y][x].a=0;
            pix[y][x].color=buf[(height-1)-(y-y_start)][x-x_start];
        }
    }

    close(pic_fd);
}

int lcd_show_text_16x32(int x_start, int y_start, unsigned char buf[16], color_t color)
{
    int i=0, j=0, x=0, y=0;
    for(y=y_start, j=0; y<600 && j<32; y++, j++)
    {
        for(x=x_start, i=7; x<1024 && i>=0; x++, i--)
        {
            if((buf[2*j+0] & (0x01<<i))!=0)
            {
                pix[y][x].a=0;
                pix[y][x].color=color;
            }
        }
        for(x, i=7; x<1024 && i>=0; x++, i--)
        {
            if((buf[2*j+1] & (0x01<<i))!=0)
            {
                pix[y][x].a=0;
                pix[y][x].color=color;
            }
        }
    }
}

